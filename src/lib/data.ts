    Array.from(name || "Guest").reduce((acc, ch) => acc + ch.charCodeAt(0) * 17, 0);
  const hue = Math.abs(hash) % 360;
  const skin = SKIN_TONES[Math.abs(hash) % SKIN_TONES.length];
